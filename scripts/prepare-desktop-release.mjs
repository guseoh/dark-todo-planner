import { readFileSync, writeFileSync } from "node:fs";

const version = process.env.TERN_VERSION?.trim();
const publicKey = process.env.TERN_UPDATER_PUBLIC_KEY?.trim();
const privateKey = process.env.TAURI_SIGNING_PRIVATE_KEY?.trim();

if (!version || !/^0\.3\.[1-9]\d*$/.test(version)) {
  throw new Error("TERN_VERSION must be a monotonically increasing 0.3.<run_number> version.");
}
if (!publicKey || !privateKey) {
  throw new Error("Signed Windows releases require TERN_UPDATER_PUBLIC_KEY and TAURI_SIGNING_PRIVATE_KEY secrets.");
}
// Tauri CLI's generated .pub value is a base64-encoded minisign public-key
// document (typically beginning with dW50...), NOT the inner RW... line.
// Validate the encoded document without printing either signing secret.
if (!/^[A-Za-z0-9+/]+={0,2}$/.test(publicKey)) {
  throw new Error("TERN_UPDATER_PUBLIC_KEY must be the base64 value generated by the Tauri signer.");
}
const decodedKey = Buffer.from(publicKey, "base64").toString("utf8");
if (!/^untrusted comment: minisign public key:/m.test(decodedKey)
  || !/^RW[A-Za-z0-9+/=]{40,}$/m.test(decodedKey)) {
  throw new Error("TERN_UPDATER_PUBLIC_KEY is not a valid Tauri minisign public-key document.");
}
const path = "src-tauri/tauri.conf.json";
const conf = JSON.parse(readFileSync(path, "utf8"));
if (conf.productName !== "Tern" || conf.plugins?.updater?.pubkey !== "__TAURI_UPDATER_PUBLIC_KEY__") {
  throw new Error("Unexpected Tauri configuration; refusing to overwrite a key or product name.");
}
conf.version = version;
const cargoPath = "src-tauri/Cargo.toml";
const cargo = readFileSync(cargoPath, "utf8");
if (!/^version = "0\.3\.0"$/m.test(cargo)) throw new Error("Unexpected Cargo version; refusing to replace.");
writeFileSync(cargoPath, cargo.replace(/^version = "0\.3\.0"$/m, `version = "${version}"`));
conf.plugins.updater.pubkey = publicKey;
writeFileSync(path, JSON.stringify(conf, null, 2) + "\n");
console.log("Prepared signed Tern release", version, "(public key injected; private key never written).");
