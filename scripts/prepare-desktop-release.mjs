import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

const versionPattern = /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/;
export function parseVersion(version) {
  if (typeof version !== "string" || !versionPattern.test(version)) throw new Error("Expected explicit stable MAJOR.MINOR.PATCH version.");
  return version.split(".").map(BigInt);
}
export function compareVersions(a, b) {
  const left = parseVersion(a);
  const right = parseVersion(b);
  for (let i = 0; i < 3; i++) {
    if (left[i] !== right[i]) return left[i] > right[i] ? 1 : -1;
  }
  return 0;
}
export function readReleaseVersion() {
  const conf = JSON.parse(readFileSync("src-tauri/tauri.conf.json", "utf8"));
  const cargo = readFileSync("src-tauri/Cargo.toml", "utf8");
  const lock = readFileSync("src-tauri/Cargo.lock", "utf8");
  const version = conf.version;
  parseVersion(version);
  const cargoVersion = cargo.match(/^\[package\]\r?\nname = "tern"\r?\nversion = "([^"]+)"/m)?.[1];
  const roots = [...lock.matchAll(/^\[\[package\]\]\r?\nname = "tern"\r?\nversion = "([^"]+)"/gm)];
  if (conf.productName !== "Tern" || cargoVersion !== version || roots.length !== 1 || roots[0][1] !== version) {
    throw new Error("Tern version mismatch: update tauri.conf.json, Cargo.toml and the root Cargo.lock package together.");
  }
  return version;
}
export function requireNewerRelease(version, latestTag) {
  if (typeof latestTag !== "string" || !latestTag.startsWith("tern-v")) throw new Error("Latest Tern release tag is missing or invalid.");
  if (compareVersions(version, latestTag.slice(6)) <= 0) throw new Error("Release version must be strictly newer than the published Tern version.");
}
function prepare() {
  const version = readReleaseVersion();
  if (process.argv.includes("--version")) { console.log(version); return; }
  if (process.argv.includes("--check-newer")) { requireNewerRelease(version, process.env.TERN_LATEST_TAG); return; }
  if (process.env.TERN_VERSION !== undefined && process.env.TERN_VERSION !== version) throw new Error("TERN_VERSION cannot override the tracked release version.");
  const publicKey = process.env.TERN_UPDATER_PUBLIC_KEY?.trim();
  const privateKey = process.env.TAURI_SIGNING_PRIVATE_KEY?.trim();
  if (!publicKey || !privateKey) throw new Error("Signed Windows releases require TERN_UPDATER_PUBLIC_KEY and TAURI_SIGNING_PRIVATE_KEY secrets.");
  if (!/^[A-Za-z0-9+/]+={0,2}$/.test(publicKey)) throw new Error("TERN_UPDATER_PUBLIC_KEY must be the base64 value generated by the Tauri signer.");
  const decodedKey = Buffer.from(publicKey, "base64").toString("utf8");
  if (!/^untrusted comment: minisign public key:/m.test(decodedKey) || !/^RW[A-Za-z0-9+/=]{40,}$/m.test(decodedKey)) throw new Error("TERN_UPDATER_PUBLIC_KEY is not a valid Tauri minisign public-key document.");
  const path = "src-tauri/tauri.conf.json";
  const conf = JSON.parse(readFileSync(path, "utf8"));
  if (conf.plugins?.updater?.pubkey !== "__TAURI_UPDATER_PUBLIC_KEY__") throw new Error("Unexpected Tauri configuration; refusing to overwrite a key.");
  conf.plugins.updater.pubkey = publicKey;
  writeFileSync(path, JSON.stringify(conf, null, 2) + "\n");
  console.log("Prepared signed Tern release", version, "(public key injected; private key never written).");
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) prepare();
